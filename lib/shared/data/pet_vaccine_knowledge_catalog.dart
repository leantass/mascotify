  static List<PetVaccineScheduleRule> rulesForSpecies(String speciesLabel) {
    final speciesKey = PetVaccineSuggestionCatalog.speciesKeyFor(speciesLabel);
    return _rules.where((rule) => rule.speciesKey == speciesKey).toList();
  }

  static bool hasUniversalCalendar(String speciesLabel) {
    final key = PetVaccineSuggestionCatalog.speciesKeyFor(speciesLabel);
    return key == 'dog' ||
        key == 'cat' ||
        key == 'horse' ||
        key == 'rabbit' ||
        key == 'ferret';
  }

  static String noGeneralCalendarMessage(String speciesLabel) {
    final key = PetVaccineSuggestionCatalog.speciesKeyFor(speciesLabel);
    switch (key) {
      case 'bird':
        return 'Sin calendario universal de vacunas para todas las aves. El seguimiento depende de especie, origen, convivencia, criadero, región y veterinario especializado.';
      case 'reptile':
        return 'Sin vacunas rutinarias generales registradas para reptiles. El seguimiento suele centrarse en hábitat, alimentación, temperatura, UVB y veterinario especializado.';
      case 'fish':
        return 'Sin vacunas hogareñas rutinarias para peces domésticos. El cuidado preventivo suele centrarse en calidad de agua, cuarentena y controles.';
      case 'rodent':
        return 'Sin vacunas rutinarias generales registradas para pequeños mamíferos. Usá carga manual si un profesional indicó una vacuna.';
      default:
        return 'No hay sugerencias automáticas para esta especie. Cargá únicamente vacunas indicadas por un veterinario.';
    }
  }

