DemoCreatorAccount _creator({
  required String id,
  required String displayName,
  required String username,
  required String profileType,
  required String bio,
  required String location,
  required int followersCount,
  required int clipsCount,
}) {
  return DemoCreatorAccount(
    id: id,
    displayName: displayName,
    username: username,
    avatarAsset: 'assets/demo/avatars/$username.png',
    bio: bio,
    location: location,
    profileType: profileType,
    createdAt: DateTime.utc(2026, 5, 1),
    followersCount: followersCount,
    clipsCount: clipsCount,
  );
}

ExploreClip _clip({
  required String id,
  required String authorId,
  required String petName,
  required String title,
  required String description,
  required String category,
  required String animalType,
  required int likes,
  required int comments,
  required int shares,
  required int hoursAgo,
  required List<String> tags,
}) {
  final creator = ClipsMockData.creatorById(authorId);
  return ExploreClip(
    id: id,
    title: title,
    description: description,
    category: category,
    animalType: animalType,
    petName: petName,
    authorId: authorId,
    authorDisplayName: creator?.displayName,
    authorUsername: creator?.username,
    demoVideoKey: id,
    likes: likes,
    comments: comments,
    shares: shares,
    createdAt: DateTime.utc(
      2026,
      5,
      26,
