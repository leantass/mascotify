  static DemoCreatorAccount? creatorById(String id) {
    for (final creator in demoCreators) {
      if (creator.id == id) return creator;
    }
    return null;
  }

  static List<DemoPetProfile> petsForCreator(String creatorId) {
    return demoPets
        .where((pet) => pet.ownerDemoAccountId == creatorId)
        .toList();
  }

  static List<ExploreClip> clipsForCreator(String creatorId) {
    return clips.where((clip) => clip.authorId == creatorId).toList();
  }

